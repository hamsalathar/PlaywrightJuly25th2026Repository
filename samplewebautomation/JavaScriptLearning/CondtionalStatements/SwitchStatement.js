/* Switch Statement */

let character = "e";

switch(character){

    case "a":
        console.log(character + "  is a vowel");
        break;
        case "e":
        console.log(character + "  is a vowel");
        break;

    case "i":
        console.log(character + "is a vowel");
        break;
    case "o":
        console.log(character+" is a vowel");
        break;
    case "u":
        console.log(character + " is a vowel");
        break;
        default:
            console.log(character + " is a consonant");
}