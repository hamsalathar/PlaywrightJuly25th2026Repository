/* Logical operators in JavaScript are used to perform logical operations on boolean values. The common logical operators include:
1. AND (&&): Returns true if both operands are true.
2. OR (||): Returns true if at least one of the operands is true.
3. NOT (!): Returns true if the operand is false, and vice versa. */


// AND operator
let age=25;
console.log(age>18 && age<30); //true because both conditions are true

//OR operator
let age1=70;
console.log(age1>18 || age1<70); //true beacuse both the conditions are true.

//NOT operator
let isLoggedIn=true;
console.log(!isLoggedIn); //false because the value of isLoggedIn is true and NOT operator negates it to false. 

