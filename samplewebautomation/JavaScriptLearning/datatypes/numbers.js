
//number data type
var a =100;
console.log(a);
console.log(typeof(a));
//In JavaScript, all decimal numbers and whole numbers are considered as number.
let b=21.567;
console.log(b);
console.log(typeof(b));

//String data type
const c="hamsa";
console.log(c);
console.log(typeof(c));

// In JavaScript, a single character is also considered as string data type.
const d='h';
console.log(d);
console.log(typeof(d));

//boolean data type
let e= true;
console.log(e);
console.log(typeof(e));

//undefined data type
let f;
console.log(f);
console.log(typeof(f));

//null data type
let g=null;
console.log(g)
console.log(typeof(g));

//symbol data type
const h=Symbol("hamsa");
console.log(h);
console.log(typeof(h));

//BigInt data type
const i =1318263164142364734565679470567n;
console.log(i);
console.log(typeof(i));

//object data type
let employee = {
    name:"hamsa",
    age:25,
    city:"bangalore"
     }
    console.log(employee);
    console.log(typeof(employee));
    

