/*Write a program based on the given month number, it should provide month name.*/

let monthNumber = 5;

switch (monthNumber) {
    case 1:
        console.log(monthNumber + " Month name is January");
        break;

    case 2:
        console.log(monthNumber + " Month name is February");
        break;

    case 3:
        console.log(monthNumber + " Month name is March");
        break;

    case 4:
        console.log(monthNumber + " Month name is April");
        break;

    case 5:
        console.log(monthNumber + " Month name is May");
        break;

    case 6:
        console.log(monthNumber + " Month name is June");
        break;

    case 7:
        console.log(monthNumber + " Month name is July");
        break;

    case 8:
        console.log(monthNumber + " Month name is August");
        break;

    case 9:
        console.log(monthNumber + " Month name is September");
        break;

    case 10:
        console.log(monthNumber + " Month name is October");
        break;

    case 11:
        console.log(monthNumber + " Month name is November");
        break;

    case 12:
        console.log(monthNumber + " Month name is December");
        break;

    default:
        console.log("Invalid month number entered");
}
